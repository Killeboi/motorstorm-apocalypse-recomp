#!/usr/bin/env python3
"""Lift the SPURS policy modules this title's LLE SPURS kernel streams into LS 0xA00.

The real (lifted) SPURS kernel DMAs a workload's policy module from its main-memory
EA into local store 0xA00 and branches there. Those blobs are raw SPU code (no ELF),
so build_spu_workloads.py never sees them and the kernel runs them interpreted.
This script wraps each blob in a minimal SPU ELF (one RX PT_LOAD at 0xA00), lifts it
with spu_lifter.py under its own symbol prefix, and emits port/spu/pm_register.c,
which registers every PM as a *verified overlay* keyed by its DMA source EA
(spu_overlay_register_verified_region): when the kernel GETs that EA into 0xA00 the
runtime compares the bytes once and then dispatches the lifted code.

PM addresses/sizes come from CellSpurs.wklInfo1[] / wklInfoSysSrv read at run time
(NOTES.md): Wws_Job 0x0123B100/0x2F80 (EBOOT), taskset 0x30023680/0x1E40 and
system service 0x30021480/0x2200 (libsre at base 0x30000000).

Run from C:/msa-port:  py -3.14 -X utf8 tools/lift_spurs_pms.py
(needs elf/EBOOT.elf and firmware/libsre_out/libsre_image.bin; outputs are local only)
"""
import json, os, struct, subprocess, sys

ROOT = os.getcwd()
LIFTER = os.path.join(ROOT, 'repo', 'tools', 'spu_lifter.py')
OUT = os.path.join(ROOT, 'port', 'spu')
LSA = 0xA00
FIRST_IMAGE_ID = 40   # build_spu_workloads.py uses 1..N for the ELF images

def eboot_bytes(va, size):
    d = open('elf/EBOOT.elf', 'rb').read()
    off = va - 0x10000                     # R-X PT_LOAD: vaddr 0x10000 at file offset 0
    return d[off:off + size]

def libsre_bytes(va, size):
    d = open('firmware/libsre_out/libsre_image.bin', 'rb').read()
    off = va - 0x30000000
    return d[off:off + size]

PMS = [
    # name,          source EA,   size,   bytes,                               extra entries
    ('pm_wwsjob',    0x0123B100, 0x2F80, lambda: eboot_bytes(0x0123B100, 0x2F80), [0xA2C]),
    ('pm_taskset',   0x30023680, 0x1E40, lambda: libsre_bytes(0x30023680, 0x1E40), [0xA70]),   # task-syscall entry: reached only via syscallAddr; must be a lifted entry or ps3recomp's HLE intercept hijacks it
    ('pm_syssrv',    0x30021480, 0x2200, lambda: libsre_bytes(0x30021480, 0x2200), []),
]

CODE_END = {'pm_taskset': 0x2700}   # LS address where the PM's code ends (data after)

def wrap_elf(code, vaddr):
    """ELF32 BE, EM_SPU (23), ET_EXEC, one PT_LOAD R+X at vaddr, entry = vaddr."""
    ehsz, phsz, data_off = 52, 32, 0x80
    eh = b'\x7fELF' + bytes([1, 2, 1, 0]) + b'\0' * 8
    eh += struct.pack('>HHIIIIIHHHHHH', 2, 23, 1, vaddr, ehsz, 0, 0, ehsz, phsz, 1, 40, 0, 0)
    ph = struct.pack('>IIIIIIII', 1, data_off, vaddr, vaddr, len(code), len(code), 5, 0x80)
    img = eh + ph
    return img + b'\0' * (data_off - len(img)) + code

def main():
    os.makedirs(OUT, exist_ok=True)
    reg = ['/* Auto-generated by tools/lift_spurs_pms.py -- local only, never committed.',
           ' * Registers the lifted SPURS policy modules as verified LS-0xA00 overlays. */',
           '#include <stdint.h>', '#include "spu_overlay_residency.h"',
           'extern void spu_begin_image(int image_id);']
    body = []
    for i, (name, ea, size, get, extra) in enumerate(PMS):
        code = get()
        assert len(code) == size, (name, len(code))
        img_id = FIRST_IMAGE_ID + i
        d = os.path.join(OUT, name)
        os.makedirs(d, exist_ok=True)
        elf = os.path.join(d, 'image.elf')
        open(elf, 'wb').write(wrap_elf(code, LSA))
        cmd = [sys.executable, '-X', 'utf8', LIFTER, elf, '--auto-functions', elf,
               '--symbol-prefix', name + '_', '--output', d,
               '--header-name', 'spu_recomp.h', '--source-name', 'spu_recomp.c',
               '--report', os.path.join(d, 'report.json')]
        if extra:
            cmd += ['--extra-funcs', ','.join(hex(x) for x in extra)]
        print('lift', name, 'ea=0x%08X size=0x%X image=%d' % (ea, size, img_id))
        r = subprocess.run(cmd, capture_output=True, text=True)
        tail = (r.stdout + r.stderr).strip().splitlines()[-6:]
        print('   ' + '\n   '.join(tail))
        if r.returncode:
            sys.exit('lifter failed for ' + name)
        # same include rewrite build_spu_workloads.py does (resolved via -I runtime/spu)
        for fn in ('spu_recomp.c', 'spu_recomp.h'):
            p = os.path.join(d, fn)
            s = open(p, encoding='utf-8').read()
            s = s.replace('"../../runtime/spu/spu_context.h"', '"spu_context.h"')
            s = s.replace('"../../runtime/spu/spu_helpers.h"', '"spu_helpers.h"')
            open(p, 'w', encoding='utf-8').write(s)
        # Span = CODE ONLY (0xA00 .. end of the last lifted function, 16-aligned). The PM blob
        # also holds data the kernel/PM DMA into at run time (taskset context at 0x2700,
        # WWS command buffer at 0xC00...); a GET from any other EA into the registered span
        # clears the residency (spu_overlay_note_get), which dropped the taskset PM and let
        # ps3recomp's HLE hijack its 0xA70 syscall entry.
        fr = json.load(open(os.path.join(d, 'report.json')))['functions']
        code_end = (max(e for s, e in fr) + 15) & ~15
        # Known data areas the auto-detection swallowed as code: the taskset PM keeps the
        # SpursTasksetContext at LS 0x2700 (taskset @0x27BC, syscallAddr @0x27C4, taskId
        # @0x27D4 -- RPCS3 cellSpursSpu.cpp, ps3recomp spu_channels.c), DMA'd per task.
        code_end = min(code_end, CODE_END.get(name, code_end))
        span = min(code_end - LSA, size)
        print('   code span 0x%X..0x%X (0x%X of 0x%X bytes)' % (LSA, LSA + span, span, size))
        reg.append('extern void %s_spu_recomp_register(void);' % name)
        reg.append('static const uint8_t %s_bytes[0x%X] = {' % (name, span))
        for k in range(0, span, 16):
            reg.append('    ' + ', '.join('0x%02X' % b for b in code[k:min(k + 16, span)]) + ',')
        reg.append('};')
        body.append('    spu_begin_image(%d); %s_spu_recomp_register();' % (img_id, name))
        body.append('    { spu_overlay_code_segment seg = { 0x%X, 0x%X, %s_bytes };' % (LSA, span, name))
        body.append('      n += spu_overlay_register_verified_region(0x%08Xu, 0x%Xu, 0x%Xu, %d, &seg, 1); }'
                    % (ea, LSA, span, img_id))
    # SPURS *task* ELFs: the LLE taskset PM DMAs each PT_LOAD from (elf EA + p_offset)
    # to p_vaddr. Their code is already lifted and registered by build_spu_workloads.py
    # (spu_workloads.c) under these image ids; only the overlay keys are added here.
    TASKS = [  # name, image id in spu_workloads.c, guest EA of the embedded ELF
        ('edgepost_mlaa',    1, 0x01170080),
        ('edgezlib_inflate', 2, 0x01178900),
        ('msngSPURS_MP3',    5, 0x01158A80),
    ]
    wl = open(os.path.join(OUT, 'spu_workloads.c'), encoding='utf-8').read()
    for name, img_id, ea in TASKS:
        assert 'spu_begin_image(%d); %s_spu_recomp_register' % (img_id, name) in wl, name
        e = open(os.path.join('spu_programs', 'images', name + '.elf'), 'rb').read()
        phoff, phn = struct.unpack('>I', e[28:32])[0], struct.unpack('>H', e[44:46])[0]
        for k in range(phn):
            t, off, va, pa, fs, ms, fl, al = struct.unpack('>8I', e[phoff + 32 * k:phoff + 32 * k + 32])
            if t != 1 or not (fl & 1) or not fs:
                continue
            sym = '%s_seg%d' % (name, k)
            reg.append('static const uint8_t %s[0x%X] = {' % (sym, fs))
            for j in range(0, fs, 16):
                reg.append('    ' + ', '.join('0x%02X' % b for b in e[off + j:off + j + 16]) + ',')
            reg.append('};')
            body.append('    { spu_overlay_code_segment seg = { 0x%X, 0x%X, %s };   /* task %s */'
                        % (va, fs, sym, name))
            body.append('      n += spu_overlay_register_verified_region(0x%08Xu, 0x%Xu, 0x%Xu, %d, &seg, 1); }'
                        % (ea + off, va, fs, img_id))
            print('task overlay', name, 'src=0x%08X lsa=0x%X span=0x%X image=%d' % (ea + off, va, fs, img_id))
        # A task RESUMED after a context switch has its LS restored from the context save
        # area, not from the ELF, so the overlay key above no longer matches and its code
        # fell back to the interpreter (Multistream's MP3 task then stopped inside the PM).
        # The taskset context names the loaded ELF (TaskInfo.elf @ LS 0x2794); map it to the
        # task's image so the dispatcher adopts it for any PC in the task region. Policy
        # image 0: our PMs are verified regions, so ctx->resident_ovl stays 0.
        body.append('    spu_taskset_register_task_elf(0x%08Xu, %d, 0);   /* %s */' % (ea, img_id, name))
    reg.append('extern void spu_taskset_register_task_elf(uint32_t elf_ea, int image_id, int policy_image_id);')
    total = len(PMS) + len(TASKS)
    reg.append('#include <stdio.h>')
    reg.append('void port_spu_pm_register_all(void)\n{\n    int n = 0;')
    reg += body
    reg.append('    fprintf(stderr, "[spu-pm] %%d/%%d SPURS policy-module + task overlays registered\\n", n, %d);'
               % total)
    reg.append('}')
    reg.append('__attribute__((constructor)) static void port_spu_pm_ctor(void) { port_spu_pm_register_all(); }')
    open(os.path.join(OUT, 'pm_register.c'), 'w', encoding='utf-8').write('\n'.join(reg) + '\n')
    print('wrote', os.path.join(OUT, 'pm_register.c'))

main()
